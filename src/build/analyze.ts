// Responsibility: analyze a schema and a named SQL catalog without importing application code.
// Boundary: an in-memory schema proves local contracts, not the contents of a deployed database.
import { Engine } from "./facts.ts";
import { emitGenerated } from "./emit.ts";
import { created, splitStatements } from "./scan.ts";
import { catalogStatement } from "./statements.ts";
import { BuildError, Typer } from "./typegen.ts";

export function analyzeSchema(schema: string, catalog: unknown, library = "solarsql") {
  if (!catalog || typeof catalog !== "object" || Array.isArray(catalog) || Object.values(catalog).some(sql => typeof sql !== "string")) {
    throw new BuildError("The query catalog must be a JSON object of names and SQL strings.");
  }
  const engine = new Engine([]);
  try {
    for (const sql of splitStatements(schema)) {
      if (!created(sql)) throw new BuildError("The schema must contain CREATE statements. Supply schema DDL without data or PRAGMAs.", sql);
      try { engine.db.exec(sql); }
      catch (e) { throw new BuildError((e as Error).message, sql); }
    }
    const typer = new Typer(engine, new Map(), { conservativeStorage: true });
    const entries = Object.entries(catalog as Record<string, string>).map(([name, sql]) => {
      if (["kind", "entries", "__proto__"].includes(name)) throw new BuildError(`Query name "${name}" is reserved. Choose another catalog name.`, sql);
      try {
        const statement = catalogStatement(sql, "read");
        return { name, key: sql, analysis: typer.analyze(statement, "schema"), origins: engine.columns(statement), accesses: engine.accesses(statement) };
      } catch (e) {
        if (e instanceof BuildError) e.locations.push(`queries.${name}`);
        throw e;
      }
    });
    // Repeated SQL names share one metadata entry, while the catalog retains every name.
    const unique = [...new Map(entries.map(entry => [entry.key, entry])).values()];
    const generated = emitGenerated({ library, module: "schema", ownBrands: [], importedBrands: [], entries: unique,
      header: "// Generated by solarsql analyze. Do not edit.\n// Run solarsql analyze with the schema, catalog, and --out path after a change." })
      + `\nexport const statements = {\n${entries.map(e => `  [${JSON.stringify(e.name)}]: ${JSON.stringify(e.key)},`).join("\n")}\n} as const;\n`;
    return { version: 1, ok: true, sqlite: engine.db.prepare("select sqlite_version() as version").get()!.version,
      contract: { types: "engine-metadata-and-static-inference", storage: "non-strict-columns-use-SqlValue", execution: "local-node-sqlite", imports: false, deploymentVerified: false },
      operations: entries.map(e => ({ name: e.name, sql: e.key, params: e.analysis.params, columns: e.analysis.columns, reads: e.analysis.reads, origins: e.origins, accesses: e.accesses })), generated };
  } finally { engine.close(); }
}
