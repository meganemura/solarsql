// Responsibility: render()'s own text format, independent of diff()'s plan
// shape, and that every reader of a rendered file still gets its statements.
// Boundary: the D1 uppercase-BEGIN/END rewrite is covered in
// trigger-migration.test.ts.
import { test } from "vitest";
import assert from "node:assert/strict";
import { DatabaseSync } from "node:sqlite";
import * as hegel from "@hegeldev/hegel";
import * as gs from "@hegeldev/hegel/generators";
import { applied, diff, introspect, open, render, shape } from "../src/build/migration.ts";
import { normalize, splitStatements } from "../src/build/scan.ts";
import { migrate } from "../src/node.ts";

test("render() trims each statement, ends each with a statement-breakpoint line, and omits the rebuild header by default", () => {
  const file = render(1, "x", ["  create table a (id)\n", "create table b (id)  "]);
  assert.deepEqual(file, {
    filename: "0001_x.sql",
    sql: '-- Migration 0001_x.sql. Generated by solarsql from the declared schema.\n'
      + 'create table a (id);\n'
      + '--> statement-breakpoint\n'
      + 'create table b (id);\n'
      + '--> statement-breakpoint\n',
  });
});

const declared = [
  `create table guard (name text not null, ok integer not null) strict`,
  `create trigger guard_check before insert on guard
  when new.ok = 0
  begin
    select raise(abort, new.name);
  end`,
];

function generate(files: string[], target: string[], sequence: number, name: string): { name: string; sql: string } {
  const plan = diff(introspect(applied(files)), introspect(open(target)));
  assert.equal(plan.kind, "ok", JSON.stringify(plan));
  if (plan.kind !== "ok") throw new Error("unreachable");
  const file = render(sequence, name, plan.statements);
  return { name: file.filename, sql: file.sql };
}

test("a generated migration with a multi-line trigger, and a later one-trigger migration, apply through migrate() and the build replay", () => {
  const first = generate([], declared, 1, "initial");
  const target = [...declared, `create trigger guard_touch after insert on guard
  begin
    select 1;
  end`];
  const second = generate([first.sql], target, 2, "touch");

  const db = new DatabaseSync(":memory:");
  assert.deepEqual(migrate(db, [first, second]), ["0001_initial.sql", "0002_touch.sql"]);
  assert.throws(() => db.exec(`insert into guard values ('refused', 0)`), /refused/);
  db.exec(`insert into guard values ('kept', 1)`);
  assert.deepEqual(db.prepare(`select name from sqlite_schema where type = 'trigger' order by name`).all().map((r) => r.name), ["guard_check", "guard_touch"]);

  assert.deepEqual(shape(introspect(applied([first.sql, second.sql]))), shape(introspect(open(target))));
});

// Statements whose text can confuse a splitter: a trigger body with inner
// semicolons, and literals that hold a semicolon or the breakpoint line.
const pool = [
  `create table t1 (id integer primary key, note text default ';')`,
  `create trigger t1_check before insert on t1\n  begin\n    select raise(abort, 'no;\n--> statement-breakpoint\n');\n    select 1;\n  end`,
  `create view v1 as select ';' as a, '--> statement-breakpoint' as b`,
  `create index t1_note on t1 (note)`,
  `pragma defer_foreign_keys = on`,
  `insert into t1 (note) values ('a;b')`,
];

test("splitStatements() reads back the statements render() wrote, in order", () => {
  hegel.test((tc) => {
    const statements = tc.draw(gs.arrays(gs.sampledFrom(pool), { maxSize: 8 }));
    const read = splitStatements(render(1, "x", statements).sql);
    assert.deepEqual(read.map(normalize), statements.map(normalize));
  });
});
